local M = {}

function M.register()
  Prefab.define('grass_platform', function(entity)
    -- Collision reaches the top of the grass cap: 0.34 centre + 0.09 radius.
    Node.add_component(entity, 'platform', { width = 4, height = 0.43 })
    draw_box(entity, 'brick', 0, 0, 0, 2, 0.34, 0.9, '#c96b32')
    draw_box(entity, 'grass', 0, 0.34, 0, 2, 0.09, 0.94, '#55c95d')
    draw_box(entity, 'soil', 0, -0.25, 0, 1.8, 0.08, 0.88, '#7b3f2b')
  end)
  Prefab.define('gear_coin', function(entity)
    Node.add_component(entity, 'gear_coin', { points = 100 })
    draw_sphere(entity, 'gear', 0, 0, 0, 0.22, '#ffd23f')
    draw_box(entity, 'tooth_h', 0, 0, 0, 0.32, 0.07, 0.08, '#ff9f1c')
    draw_box(entity, 'tooth_v', 0, 0, 0, 0.07, 0.32, 0.08, '#ff9f1c')
    drawing_set_animation(entity, 'gear', 'pulse', 4, 0.08)
  end)
  Prefab.define('beetle', function(entity)
    Node.add_component(entity, 'walker', { origin = 0, range = 1.4, direction = 1, speed = 1.25 })
    draw_sphere(entity, 'shell', 0, 0.28, 0, 0.34, '#6c3fb5')
    draw_sphere(entity, 'face', 0.25, 0.22, 0, 0.22, '#f7c873')
    draw_box(entity, 'foot_a', -0.18, -0.02, 0, 0.16, 0.08, 0.18, '#3d245f')
    draw_box(entity, 'foot_b', 0.22, -0.02, 0, 0.16, 0.08, 0.18, '#3d245f')
    draw_box(entity, 'antenna', 0.3, 0.56, 0, 0.04, 0.2, 0.04, '#ff8a3d')
  end)
  Prefab.define('spring', function(entity)
    Node.add_component(entity, 'spring', { power = 10.5 })
    draw_box(entity, 'base', 0, 0.1, 0, 0.34, 0.1, 0.5, '#2676d8')
    draw_box(entity, 'coil', 0, 0.28, 0, 0.16, 0.18, 0.35, '#f5f1d8')
    draw_box(entity, 'cap', 0, 0.48, 0, 0.42, 0.08, 0.52, '#ff5d55')
  end)
  Prefab.define('checkpoint', function(entity)
    Node.add_component(entity, 'checkpoint', { active = false })
    draw_box(entity, 'post', 0, 0.55, 0, 0.07, 0.6, 0.07, '#f5f1d8')
    draw_box(entity, 'pennant', 0.28, 0.95, 0, 0.3, 0.16, 0.06, '#38bdf8')
  end)
  Prefab.define('finish_bell', function(entity)
    Node.add_component(entity, 'finish', {})
    draw_box(entity, 'pole', 0, 0.8, 0, 0.08, 0.85, 0.08, '#f5f1d8')
    draw_sphere(entity, 'bell', 0, 1.62, 0, 0.3, '#ffd23f')
    draw_box(entity, 'flag', 0.38, 1.25, 0, 0.4, 0.22, 0.06, '#ff5d55')
    drawing_set_animation(entity, 'bell', 'pulse', 2.5, 0.08)
  end)
end

return M
